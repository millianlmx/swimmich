"""Immich API stub for the share-quality / caches scenario (`ShareAndCachesUITests`).

Thin on purpose: the OAuth handshake, the server config, the user and the
introspection routes (`/__requests`, `/__reset`) come from `immich_stub_base`.
This file adds what lot L-27 (share quality, log level, image cache, offline
purge alerts) needs to observe ON THE WIRE:

    python3 UITests/stubs/immich_stub_share_caches.py 8421

    .omp/orchestration/uitest.sh <worktree> /tmp/immich-orchestration/share-caches.uitest.log \\
        UITests/stubs/immich_stub_share_caches.py ShareAndCachesUITests/test_AC_50 --erase

WHAT IT SERVES
    * a timeline of ONE day with two assets: the photo `P1` (`IMG_0001.HEIC`,
      `image/heic`) and the video `V1` (`IMG_0002.MOV`, `video/quicktime`), with
      their `GET /api/assets/{id}` detail carrying those names and mime types;
    * an album `ALBUM` of 30 photos (`POST /api/search/metadata` with `albumIds`)
      whose thumbnails are decodable PNGs of deterministic NOISE (incompressible,
      about 150 KB each) served `Cache-Control: private, max-age=86400`. They,
      and only they, are cacheable: the app's disk image cache then exceeds 1 MB
      after one visit, which is what the "Image Cache" row reads. Every other
      asset body keeps the base's `no-store` (see THE THUMBNAIL TRAP in
      `immich_stub_base.py`; `/__reset` still rotates `STATE["thumbhash"]`);
    * `GET /api/assets/{P1|V1}/original`: about 2 MB generated (a noise PNG, so an
      offline copy of it still decodes), the real `Content-Type`, a full
      `Content-Length`.

CONTROL ROUTES (all back to their default by `/__reset`)
    /control/original?mode=ok|fail|slow&status=500&seconds=10
        `fail`: the original answers `status`. `slow`: the body is sent in
        chunks spread over `seconds` seconds (the headers and the first bytes go
        out at once, so the client shows a determinate progress card).
    /control/preview?mode=ok|fail&status=500
        The preview is `GET /api/assets/{id}/thumbnail?size=preview`. `fail`: it
        answers `status`. Set it AFTER the viewer displayed its photo: the viewer
        shows the same preview.
    /control/network?down=1|0
        `down=1`: every `/api/*` request answers 503, like
        `immich_stub_offline.py`'s `/__network`. `/__*` and `/control/*` stay up.

WHAT IS LOGGED
    The base's journal: every non-`/__*` request, `/control/*` included.
"""
import random
import time
import zlib

from immich_stub_base import (
    ME_USER, STATE, TIMELINE_ASSETS, TIMELINE_DAY, Response, StubHandler, asset,
    bucket_payload, main, router,
)

P1 = TIMELINE_ASSETS[0]
V1 = TIMELINE_ASSETS[1]
TIMELINE = [P1, V1]
VIDEO_MS = 7000

ALBUM = "22222222-2222-4222-8222-000000000027"
ALBUM_NAME = "Cache Album"
ALBUM_PHOTOS = [f"bbbbbbbb-1111-4111-8111-{i:012d}" for i in range(1, 31)]

ORIGINALS = {
    P1: ("image/heic", "IMG_0001.HEIC"),
    V1: ("video/quicktime", "IMG_0002.MOV"),
}

THUMB_SIDE = 224      # 224 * 224 * 3 bytes of noise: ~150 KB per album thumbnail
ORIGINAL_SIDE = 830   # 830 * 830 * 3 bytes of noise: ~2.0 MB per original
SLOW_CHUNKS = 20

NO_STORE = {"Cache-Control": "no-store"}
CACHEABLE = {"Cache-Control": "private, max-age=86400"}


# MARK: - Generated bytes

_noise_cache = {}


def noise_png(seed, side):
    """A real, decodable PNG whose pixels are deterministic noise per `seed`.

    Noise on purpose: it does not compress, so the byte count is the one asked
    for (a flat colour would shrink to a few hundred bytes and the disk cache
    would never reach 1 MB). Memoised: every request of one id returns the
    same bytes, like a real server.
    """
    key = (seed, side)
    cached = _noise_cache.get(key)
    if cached is not None:
        return cached
    rng = random.Random(seed)
    raw = b"".join(b"\x00" + rng.randbytes(side * 3) for _ in range(side))

    def chunk(kind, data):
        payload = kind + data
        return (len(data).to_bytes(4, "big") + payload
                + (zlib.crc32(payload) & 0xFFFFFFFF).to_bytes(4, "big"))

    body = (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", side.to_bytes(4, "big") + side.to_bytes(4, "big")
                    + bytes((8, 2, 0, 0, 0)))
            + chunk(b"IDAT", zlib.compress(raw, 1))
            + chunk(b"IEND", b""))
    _noise_cache[key] = body
    return body


# MARK: - Streaming response (the slow original)


class StreamedResponse(Response):
    """A 200 whose body goes out in `chunks`, `pause` seconds apart. The base's
    `_send` only knows complete bodies: see `_send_streamed` below."""

    __slots__ = ("chunks", "pause", "length")

    def __init__(self, chunks, pause, length, ctype, headers=None):
        super().__init__(b"", status=200, ctype=ctype, headers=headers)
        self.chunks = chunks
        self.pause = pause
        self.length = length


_base_send = StubHandler._send


def _send_streamed(self, response):
    if not isinstance(response, StreamedResponse):
        return _base_send(self, response)
    try:
        self.send_response(response.status)
        self.send_header("Content-Type", response.ctype)
        self.send_header("Content-Length", str(response.length))
        for name, value in response.headers.items():
            self.send_header(name, value)
        self.send_header("Connection", "close")
        self.end_headers()
        for index, chunk in enumerate(response.chunks):
            if index:
                time.sleep(response.pause)
            self.wfile.write(chunk)
            self.wfile.flush()
    except (BrokenPipeError, ConnectionResetError):
        # The client cancelled: that is the scenario, not a stub failure.
        self.close_connection = True


StubHandler._send = _send_streamed


# MARK: - State and control routes


def _defaults():
    STATE["original"] = {"mode": "ok", "status": 500, "seconds": 10.0}
    STATE["preview"] = {"mode": "ok", "status": 500}
    STATE["down"] = False


_defaults()


@router.reset
def fresh():
    _defaults()


def _int(value, default):
    try:
        return int(value)
    except (TypeError, ValueError):
        return default


@router.get("/control/original")
def control_original(req):
    mode = req.params.get("mode", "ok")
    STATE["original"] = {
        "mode": mode if mode in ("ok", "fail", "slow") else "ok",
        "status": _int(req.params.get("status"), 500),
        "seconds": float(_int(req.params.get("seconds"), 10)),
    }
    return Response(STATE["original"])


@router.get("/control/preview")
def control_preview(req):
    mode = req.params.get("mode", "ok")
    STATE["preview"] = {
        "mode": mode if mode in ("ok", "fail") else "ok",
        "status": _int(req.params.get("status"), 500),
    }
    return Response(STATE["preview"])


@router.get("/control/network")
def control_network(req):
    STATE["down"] = req.params.get("down") == "1"
    return Response({"down": STATE["down"]})


# A dead server answers 503 on every `/api/*`, whatever the route: the router has
# no middleware, so the guard wraps `handle` itself (the base reads `router.handle`
# at every request).
_route = router.handle


def _guarded(request):
    if STATE["down"] and request.path.startswith("/api/"):
        return Response({"error": "offline"}, status=503)
    return _route(request)


router.handle = _guarded


def _failure(status):
    return Response({"error": "stub failure", "message": "stub: forced failure"}, status=status)


# MARK: - The timeline


@router.get("/api/timeline/buckets")
def buckets(req):
    return Response([{"timeBucket": TIMELINE_DAY, "count": len(TIMELINE)}])


@router.get("/api/timeline/bucket")
def one_day(req):
    """One day, two tiles; every parallel array has the two entries (the app zips
    them by index)."""
    if req.params.get("timeBucket") != TIMELINE_DAY:
        return None
    payload = bucket_payload(TIMELINE)
    payload["isImage"][1] = False
    payload["duration"][1] = VIDEO_MS
    return Response(payload)


# MARK: - Assets


def detail(aid):
    """`GET /api/assets/{id}` of P1 and V1: the file name and mime type a real
    server reports (they decide the share sheet's file name and type)."""
    mime, name = ORIGINALS[aid]
    dto = asset(aid)
    dto.update({
        "originalFileName": name,
        "originalMimeType": mime,
        "originalPath": f"/x/{name}",
    })
    if aid == V1:
        dto.update({"type": "VIDEO", "duration": VIDEO_MS})
    return dto


def original(aid):
    mode = STATE["original"]["mode"]
    if mode == "fail":
        return _failure(STATE["original"]["status"])
    mime = ORIGINALS[aid][0]
    body = noise_png(aid, ORIGINAL_SIDE)
    if mode == "slow":
        size = -(-len(body) // SLOW_CHUNKS)
        pieces = [body[i:i + size] for i in range(0, len(body), size)]
        pause = STATE["original"]["seconds"] / max(len(pieces) - 1, 1)
        return StreamedResponse(pieces, pause, len(body), mime, headers=NO_STORE)
    return Response(body, ctype=mime, headers=NO_STORE)


@router.prefix("GET", "/api/assets/")
def assets(req):
    parts = req.rest.split("/")
    aid = parts[0]
    if len(parts) == 1:
        return Response(detail(aid)) if aid in ORIGINALS else None
    if len(parts) != 2:
        return None
    if parts[1] == "original" and aid in ORIGINALS:
        return original(aid)
    if parts[1] == "thumbnail":
        if req.params.get("size") == "preview" and STATE["preview"]["mode"] == "fail":
            return _failure(STATE["preview"]["status"])
        if aid in ALBUM_PHOTOS:
            return Response(noise_png(aid, THUMB_SIDE), ctype="image/png", headers=CACHEABLE)
    return None


# MARK: - The album


def album_dto():
    owner = {k: ME_USER[k] for k in ("id", "name", "email", "profileImagePath",
                                     "avatarColor", "profileChangedAt")}
    return {
        "id": ALBUM, "albumName": ALBUM_NAME, "description": "",
        "createdAt": "2026-01-01T00:00:00.000Z", "updatedAt": "2026-01-01T00:00:00.000Z",
        "albumThumbnailAssetId": None, "shared": False, "hasSharedLink": False,
        "assetCount": len(ALBUM_PHOTOS), "isActivityEnabled": False, "order": "desc",
        "ownerId": owner["id"], "owner": owner, "albumUsers": [],
    }


@router.get("/api/albums")
def albums(req):
    # `?shared=true` is the second read of the Albums tab: nothing is shared, so
    # the album is not listed twice.
    return Response([] if req.params.get("shared") == "true" else [album_dto()])


@router.prefix("GET", "/api/albums/")
def album_detail(req):
    if not req.rest or "/" in req.rest:
        return None
    if req.rest != ALBUM:
        return Response({"error": "not found", "path": req.path}, status=404)
    return Response(album_dto())


def _page(ids):
    items = [asset(aid) for aid in ids]
    return Response({"assets": {"count": len(items), "items": items,
                                "nextPage": None, "nextCursor": None}})


@router.post("/api/search/metadata")
def metadata(req):
    body = req.body or {}
    album_ids = body.get("albumIds") or (body.get("filter") or {}).get("albumIds") or []
    return _page(ALBUM_PHOTOS if album_ids[:1] == [ALBUM] else [])


if __name__ == "__main__":
    main(label="share-caches")
